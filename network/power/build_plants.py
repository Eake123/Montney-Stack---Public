"""Build network/power/plants_<region>.geojson: every public generator >= MIN_MW in the 13 regions (L-106, REGIONS §8).

Static reference data: downloaded once by this script (cached in <home>/cache/plants for 30 days) and committed as
built GeoJSON. It is never polled by the runner.

    uv run python network/power/build_plants.py [--min-mw 5] [--refresh]

* Region: ``montney.regions.region_of(lon, lat, country=, member=)`` (REGIONS §1 rule 1): a US plant with
  ``country="US", member="US-<its state>"`` (an Ohio plant lands nowhere; a Michigan plant on the St. Clair River can't
  land in Ontario), a Canadian (OSM) plant with ``country="CA"``. An offshore US plant beyond the coast tolerance
  (South Fork, Vineyard Wind) goes to the region holding its state. Plants outside every region are left out.
* Fuel: ``fuel_group`` is a FUELS key (montney/regions.py); ``fuel`` is the sprite key (web/sprites.js FUEL_KIND): the
  gas sub-kinds (combined_cycle, simple_cycle, cogeneration, gas_fired_steam) where the technology says so, else the
  FUELS key.
* Existing plants (network/power/*.geojson, type plant; today all Canadian: AB, BC, ON) are never duplicated: a Canadian
  (OSM) inventory plant within MATCH_KM of an existing one with the same fuel group, or with a matching name within
  3 x MATCH_KM, is dropped, and the existing feature (id, live series) stays as it is. A US (EIA) plant never merges
  into a Canadian feature (the St. Clair / Detroit rivers put US and Ontario plants a few km apart). The build report
  lists every merge.
* Est. utilisation: a US plant whose BA reports its fuel gets ``util_est`` = ``eia930.<ba>.util.<fuel_group>`` and
  ``quality: "estimate"`` (the sprite animates with the BA's fuel output, marked est., never smoke).
* Nuclear (PLAN 10b, L-108): a US nuclear plant whose reactors NRC reports gets ``value`` / ``capacity`` =
  ``nrc.plant.eia_<id>.mw`` / ``.capacity`` (power_nrc: each unit's daily power level x its net summer MW, summed) and a
  ``basis`` saying what that is, instead of the BA's fleet estimate: its glow and motion follow its own reactors.
* Zoom: zoomed in only. ``callout.priority`` 2 (tier 2) for plants >= BIG_MW, else 3 (tier 3); the box shows the
  nameplate capacity. US plants carry ``ba`` (EIA-930 balancing authority) for the est. utilisation (REGIONS §8).
* Size: one /api/network payload carries every plant, so features are lean and the default cut is >= 5 MW.
"""

from __future__ import annotations

import argparse
import json
import math
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

OUT_DIR = ROOT / "network" / "power"
FUELS = ("gas", "coal", "nuclear", "hydro", "pumped_storage", "wind", "solar", "battery", "oil", "biomass",
         "geothermal", "other")
GAS_SUBKINDS = ("combined_cycle", "simple_cycle", "cogeneration", "gas_fired_steam")
MATCH_KM = 2.0
BIG_MW = 300.0                  # plants this big show one zoom level earlier (tier 2 vs 3)
GENERATED = "generated by network/power/build_plants.py: do not edit by hand"
CAPACITY = OUT_DIR / "eia930_capacity.json"         # nameplate per (EIA-930 BA, fuel): write_capacity()


def km(a: tuple[float, float], b: tuple[float, float]) -> float:
    (lon1, lat1), (lon2, lat2) = a, b
    p = math.pi / 180
    h = (math.sin((lat2 - lat1) * p / 2) ** 2
         + math.cos(lat1 * p) * math.cos(lat2 * p) * math.sin((lon2 - lon1) * p / 2) ** 2)
    return 12742 * math.asin(math.sqrt(h))


def norm(name: str) -> set[str]:
    stop = {"power", "plant", "station", "generating", "energy", "centre", "center", "project", "facility", "the",
            "llc", "inc", "gs", "ngs", "cogeneration", "cogen", "wind", "solar", "farm", "hydro", "dam"}
    return {w for w in re.findall(r"[a-z0-9]+", name.lower()) if w not in stop and len(w) > 2}


def group_of(fuel: str) -> str:
    f = (fuel or "").split("+")[0].strip().lower().replace("-", "_").replace(" ", "_")
    return "gas" if f in GAS_SUBKINDS or f in ("cogen", "coal_to_gas") else (f if f in FUELS else "other")


def existing_plants() -> list[dict]:
    out = []
    for p in sorted(OUT_DIR.glob("*.geojson")):
        if p.name.startswith("plants_"):
            continue                                          # our own output: never match against it
        for f in json.loads(p.read_text(encoding="utf-8"))["features"]:
            pr = f["properties"]
            if pr.get("type") == "plant" and f["geometry"]["type"] == "Point":
                out.append({"id": pr["id"], "name": pr.get("name", ""), "group": group_of(pr.get("fuel", "")),
                            "lonlat": tuple(f["geometry"]["coordinates"][:2]), "file": p.name})
    return out


def match_existing(rec: dict, existing: list[dict]) -> dict | None:
    best = None
    for e in existing:
        d = km(rec["lonlat"], e["lonlat"])
        if d > MATCH_KM * 3:
            continue
        same_name = bool(norm(rec["name"]) & norm(e["name"])) and e["group"] == rec["group"]
        if (d <= MATCH_KM and e["group"] == rec["group"]) or (same_name and d <= MATCH_KM * 3):
            if best is None or d < best[0]:
                best = (d, e)
    return best[1] if best else None


def make_region_of(outlines: Path | None):
    """region_of(lon, lat, country, member) from montney.regions (REGIONS §1 rule 1): only regions with territory in
    ``country``, and, with ``member`` (ISO 3166-2, e.g. US-MI), only regions holding that state, so a Michigan plant on
    the St. Clair River can't land in Ontario and an Ohio plant lands nowhere (Reviewer on #408 / #411)."""
    from montney.regions import region_of
    fc = json.loads(outlines.read_text(encoding="utf-8")) if outlines else None
    return lambda lon, lat, country, member=None: region_of(lon, lat, country=country, member=member, outlines=fc)


SHORT_CITE = {"eia": "EIA-860M (public domain; month on the collection)", "osm": "OpenStreetMap contributors (ODbL)"}


def ba_capacity() -> dict[str, dict[str, float]]:
    """The committed eia930_capacity.json (written by write_capacity below on the previous build)."""
    return json.loads(CAPACITY.read_text(encoding="utf-8"))["ba"] if CAPACITY.exists() else {}


def nrc_plant(rec: dict) -> dict | None:
    """value / capacity / basis for a US nuclear plant whose units NRC reports (power_nrc PLANTS), else None."""
    if rec.get("source") != "eia" or rec.get("group") != "nuclear":
        return None
    from montney.connectors.power_nrc import PLANT_BASIS, PLANTS, plant_sid
    try:
        pid = int(rec["key"])
    except (TypeError, ValueError):
        return None
    if pid not in PLANTS:
        return None
    return {"value": plant_sid(pid, "mw"), "capacity": plant_sid(pid, "capacity"), "basis": PLANT_BASIS}


def feature(rec: dict, region: str, capacity: dict | None = None) -> dict:
    """Lean on purpose (one /api/network payload carries every plant): the full citation is on the collection."""
    label = rec["name"] if len(rec["name"]) <= 26 else rec["name"][:25] + "…"
    props = {
        "id": f"power.plant.{rec['source']}_{rec['key']}", "kind": "node", "system": "power", "type": "plant",
        "name": rec["name"], "fuel": rec["fuel"], "fuel_group": rec["group"], "nameplate_mw": round(rec["mw"], 1),
        "source": SHORT_CITE[rec["source"]], "location_precision": "site",
        "callout": {"label": f"{label} · {rec['mw']:,.0f} MW", "priority": 2 if rec["mw"] >= BIG_MW else 3},
    }
    nrc = nrc_plant(rec)
    if rec.get("ba"):                       # the EIA-930 balancing authority
        ba = str(rec["ba"]).lower()
        props["ba"] = rec["ba"]
    if nrc:                                 # measured per reactor (daily), not the BA's fleet estimate
        props.update(nrc)
    elif rec.get("ba"):
        if (capacity or {}).get(ba, {}).get(rec["group"], 0) >= 1.0:
            # est. utilisation = the BA's generation of this fuel / its EIA-860M nameplate (power_eia930_gen): the
            # sprite animates with it, always marked est., a steady glow, never smoke (Reviewer on #412)
            props["util_est"] = f"eia930.{ba}.util.{rec['group']}"
            props["quality"] = "estimate"
    if rec.get("status") == "standby":
        props["status"] = "standby"
    return {"type": "Feature", "geometry": {"type": "Point", "coordinates": [round(rec["lonlat"][0], 4),
                                                                              round(rec["lonlat"][1], 4)]},
            "properties": props}


def build(records: list[dict], region_of, min_mw: float) -> tuple[dict[str, list[dict]], dict]:
    existing = existing_plants()
    capacity = ba_capacity()
    from montney.regions import load as load_regions
    state_region = {m: rid for rid, reg in load_regions().items() for m in reg.members if m.startswith("US-")}
    by_region: dict[str, list[dict]] = defaultdict(list)
    report = {"in": len(records), "small": 0, "outside": 0, "merged": [], "kept": Counter(), "fuels": Counter()}
    seen = set()
    for rec in records:
        if rec["mw"] < min_mw:
            report["small"] += 1
            continue
        if rec["source"] == "eia":
            member = f"US-{rec.get('state') or ''}"
            r = region_of(*rec["lonlat"], country="US", member=member)
            if r is None:                          # offshore (South Fork, Vineyard Wind) beyond the 0.3 deg coast
                r = state_region.get(member)        # tolerance: the region holding its state (Ohio: still none)
        else:                                      # OSM has no reliable province tag: Canadian regions only
            r = region_of(*rec["lonlat"], country="CA")
        if r is None:
            report["outside"] += 1
            continue
        e = match_existing(rec, existing) if rec["source"] == "osm" else None   # existing plants are all Canadian:
        if e is not None:                                                      # a US plant never merges into one
            report["merged"].append(f"{rec['name']} ({rec['mw']:,.0f} MW) -> {e['id']} [{e['file']}]")
            continue
        f = feature(rec, r, capacity)
        if f["properties"]["id"] in seen:
            continue
        seen.add(f["properties"]["id"])
        by_region[r].append(f)
        report["kept"][r] += 1
        report["fuels"][rec["group"]] += 1
    return by_region, report


def write_capacity(eia: list[dict], cite: str) -> Path:
    """Nameplate MW per (EIA-930 balancing authority, FUELS group), from every operating/standby EIA-860M plant (any
    size, any state). The denominator of the est. utilisation eia930.<ba>.util.<fuel> = gen / nameplate (REGIONS §8;
    montney/connectors/power_eia930.py)."""
    cap: dict[str, Counter] = defaultdict(Counter)
    for r in eia:
        if r.get("ba"):
            cap[str(r["ba"]).lower()][r["group"]] += r["mw"]
    doc = {"_generated": GENERATED, "_source": cite, "unit": "MW",
           "ba": {b: {f: round(v, 1) for f, v in sorted(c.items())} for b, c in sorted(cap.items())}}
    CAPACITY.write_text(json.dumps(doc, indent=1, ensure_ascii=True) + chr(10), encoding="utf-8", newline=chr(10))
    return CAPACITY


def write(by_region: dict[str, list[dict]], cite: str) -> list[Path]:
    paths = []
    for old in OUT_DIR.glob("plants_*.geojson"):
        old.unlink()
    for r, feats in sorted(by_region.items()):
        feats.sort(key=lambda f: (-f["properties"]["nameplate_mw"], f["properties"]["id"]))
        fc = {"type": "FeatureCollection", "name": f"Power plants in region {r} (inventory, L-106)",
              "_generated": GENERATED, "_source": cite, "features": feats}
        p = OUT_DIR / f"plants_{r}.geojson"
        p.write_text(json.dumps(fc, separators=(",", ":"), ensure_ascii=True) + "\n", encoding="utf-8", newline="\n")
        paths.append(p)
    return paths


# ------------------------------------------------------------------ sources
# EIA-860M's URL, citation, Technology -> FUELS map and sheet reader are shared with the capacity connector
# (montney/connectors/power_capacity_us.py): montney/eia860m.py.
from montney.eia860m import EIA860M_URL, EIA_CITE, EIA_TECH, STATUSES, operating  # noqa: E402
OSM_CITE = "OpenStreetMap contributors (ODbL), power=plant, Overpass API query of {date}"
OVERPASS = ("https://overpass-api.de/api/interpreter", "https://overpass.kumi.systems/api/interpreter")
CA_PROVINCES = ("CA-AB", "CA-BC", "CA-SK", "CA-MB", "CA-ON", "CA-QC")

OSM_SOURCE = {"hydro": "hydro", "solar": "solar", "wind": "wind", "gas": "gas", "biomass": "biomass",
              "biogas": "biomass", "biofuel": "biomass", "waste": "biomass", "diesel": "oil", "oil": "oil",
              "nuclear": "nuclear", "coal": "coal", "battery": "battery", "geothermal": "geothermal"}


def load_eia860m(path: Path, month: str, year: int) -> list[dict]:
    """Operating (OP) and standby (SB) generators, summed per plant; the plant's fuel is its largest technology."""
    plants: dict[str, dict] = {}
    for r in operating(path.read_bytes()):
        pid = r["Plant ID"]
        status = r["Status"]
        if not status.startswith(STATUSES):
            continue
        tech = r["Technology"]
        if tech not in EIA_TECH:
            raise SystemExit(f"EIA-860M: unmapped Technology {tech!r} (add it to EIA_TECH in montney/eia860m.py)")
        mw = float(r["Nameplate Capacity (MW)"] or 0)
        p = plants.setdefault(pid, {"name": r["Plant Name"], "state": r["Plant State"],
                                    "lonlat": (float(r["Longitude"]), float(r["Latitude"])),
                                    "operator": r["Entity Name"],
                                    "ba": r["Balancing Authority Code"] or None,
                                    "tech_mw": Counter(), "chp": False, "op": False})
        p["tech_mw"][tech] += mw
        p["chp"] |= "CHP" in r["Sector"]
        p["op"] |= status.startswith("(OP)")
    out = []
    for pid, p in plants.items():
        tech = p["tech_mw"].most_common(1)[0][0]
        fuel, group = EIA_TECH[tech]
        if group == "gas" and p["chp"]:
            fuel = "cogeneration"
        out.append({"source": "eia", "key": str(pid), "src_id": f"EIA plant {pid}", "name": p["name"],
                    "lonlat": p["lonlat"], "mw": sum(p["tech_mw"].values()), "fuel": fuel, "group": group,
                    "tech": tech, "operator": p["operator"], "state": p["state"], "ba": p["ba"],
                    "status": "operating" if p["op"] else "standby",
                    "cite": EIA_CITE.format(month=month.title(), year=year)})
    return out


def parse_mw(s: str) -> float | None:
    m = re.match(r"^\s*([\d.,]+)\s*(mw|kw|gw)?\s*$", (s or "").split(";")[0], re.I)
    if not m:
        return None
    v = float(m.group(1).replace(",", ""))
    unit = (m.group(2) or "mw").lower()
    return v / 1000 if unit == "kw" else v * 1000 if unit == "gw" else v


INTAKE_RE = re.compile(r"(prise d'eau|water intake|intake)", re.I)


def load_osm(path: Path, date: str) -> tuple[list[dict], Counter]:
    """OSM power=plant in the Canadian provinces. A plant without a parseable MW is left out (counted)."""
    skipped = Counter()
    out = []
    for e in json.loads(path.read_text(encoding="utf-8"))["elements"]:
        t = e.get("tags", {})
        src = (t.get("plant:source") or "").split(";")[0].strip().lower()
        group = OSM_SOURCE.get(src)
        mw = parse_mw(t.get("plant:output:electricity", ""))
        c = e.get("center") or ({"lon": e["lon"], "lat": e["lat"]} if "lon" in e else None)
        if group is None or mw is None or c is None:
            skipped["no fuel" if group is None else "no MW" if mw is None else "no location"] += 1
            continue
        if t.get("plant:method") == "water-pumped-storage":
            group = "pumped_storage"
        name = t.get("name") or t.get("operator") or f"OSM {e['type']} {e['id']}"
        if INTAKE_RE.search(name):                      # a dam's intake tagged as a plant: the powerhouse is its own
            skipped["intake, not a plant"] += 1          # feature, so it would count twice (Reviewer on #500)
            continue
        fuel = group
        if group == "gas" and re.search(r"cogen|chp|co-gen", name, re.I):
            fuel = "cogeneration"
        out.append({"source": "osm", "key": f"{e['type'][0]}{e['id']}", "src_id": f"OSM {e['type']} {e['id']}",
                    "name": name, "lonlat": (float(c["lon"]), float(c["lat"])), "mw": mw, "fuel": fuel,
                    "group": group, "tech": t.get("plant:method", ""), "operator": t.get("operator", ""),
                    "state": "", "status": "operating", "cite": OSM_CITE.format(date=date)})
    return out, skipped


def fetch(cache: Path, month: str, year: int, refresh: bool) -> tuple[Path, Path]:
    """Download once into the cache (30 days); a cached copy is reused. Two requests in all."""
    import time

    import httpx
    cache.mkdir(parents=True, exist_ok=True)
    xlsx, osm = cache / f"eia860m_{month}_{year}.xlsx", cache / "osm_ca_power_plants.json"

    def fresh(p: Path) -> bool:
        return p.exists() and time.time() - p.stat().st_mtime < 30 * 86400 and not refresh

    ua = {"User-Agent": "MontneyStack/0.1 (https://github.com/Eake123/Montney-Stack)"}
    if not fresh(xlsx):
        r = httpx.get(EIA860M_URL.format(month=month, year=year), headers=ua, timeout=180, follow_redirects=True)
        r.raise_for_status()
        if not r.content.startswith(b"PK"):
            raise SystemExit(f"EIA-860M {month} {year}: not an xlsx (the month may not be released yet)")
        xlsx.write_bytes(r.content)
    if not fresh(osm):
        q = ("[out:json][timeout:180];(" + "".join(f'area["ISO3166-2"="{p}"];' for p in CA_PROVINCES)
             + ')->.p;nwr["power"="plant"](area.p);out center tags;')
        for url in OVERPASS:                                    # one try per mirror, no retry loop
            try:
                r = httpx.post(url, data={"data": q}, headers=ua, timeout=240)
                if r.status_code == 200 and r.json().get("elements"):
                    osm.write_text(r.text, encoding="utf-8")
                    break
            except (httpx.HTTPError, ValueError):
                continue
        else:
            raise SystemExit("Overpass: no answer from either mirror")
    return xlsx, osm


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--outlines", type=Path, help="region outlines (default: network/region/outlines.geojson)")
    ap.add_argument("--min-mw", type=float, default=5.0, help="5 MW keeps /api/network lean (see the PR)")
    ap.add_argument("--month", default="september", help="EIA-860M month (the latest released)")
    ap.add_argument("--year", type=int, default=2026)
    ap.add_argument("--cache", type=Path, default=None)
    ap.add_argument("--refresh", action="store_true", help="re-download even if the cache is < 30 days old")
    ap.add_argument("--dry-run", action="store_true", help="report only; write nothing")
    a = ap.parse_args(argv)
    from datetime import date

    from montney import paths
    cache = a.cache or paths.home() / "cache" / "plants"
    xlsx, osm = fetch(cache, a.month, a.year, a.refresh)
    osm_date = date.fromtimestamp(osm.stat().st_mtime).isoformat()
    eia = load_eia860m(xlsx, a.month, a.year)
    ca, skipped = load_osm(osm, osm_date)
    by_region, rep = build(eia + ca, make_region_of(a.outlines), a.min_mw)
    cite = EIA_CITE.format(month=a.month.title(), year=a.year) + "; Canada: " + OSM_CITE.format(date=osm_date)
    print(f"inventory: EIA {len(eia)} plants + OSM {len(ca)} (OSM left out: {dict(skipped)})")
    print(f"below {a.min_mw} MW: {rep['small']}, outside every region: {rep['outside']}, "
          f"merged into existing features: {len(rep['merged'])}")
    print("kept by region:", dict(sorted(rep["kept"].items())), "total", sum(rep["kept"].values()))
    print("kept by fuel:", dict(rep["fuels"].most_common()))
    for m in rep["merged"]:
        print("  merged:", m)
    if not a.dry_run:
        files = write(by_region, cite) + [write_capacity(eia, EIA_CITE.format(month=a.month.title(), year=a.year))]
        print("wrote", ", ".join(p.name for p in files))


if __name__ == "__main__":
    main()
